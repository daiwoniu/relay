import assert from 'node:assert/strict';
import path from 'node:path';
import test from 'node:test';
import initSqlJs from 'sql.js';
import { SQLiteDB } from './index.js';
import { createSessionHostContextDelivery } from './session-host-context.js';

test('送达标记保存到既有 metadata，重载后去重且保留其他引擎信息', async () => {
  const SQL = await initSqlJs({ locateFile: () => path.resolve('node_modules/sql.js/dist/sql-wasm.wasm') });
  const raw = new SQL.Database();
  raw.exec(`CREATE TABLE sessions (id TEXT PRIMARY KEY, engine TEXT, engine_session_id TEXT, engine_metadata TEXT, deleted_at INTEGER, context_compaction_count INTEGER DEFAULT 0);
    INSERT INTO sessions VALUES ('relay', 'codex', 'thread', '{"existing":{"value":1}}', NULL, 0);`);
  const db = new SQLiteDB(raw, ':memory:');
  let snapshot: Uint8Array | undefined;
  db.saveToFile = () => { snapshot = raw.export(); };
  const state = createSessionHostContextDelivery(db, 'relay', 'codex', 'thread');
  assert.equal(state.delivered, false);
  state.onDelivered('thread');
  assert.equal(snapshot, undefined);
  assert.equal(db.flushPendingSave(), true);
  assert.ok(snapshot);
  const reloadedRaw = new SQL.Database(snapshot);
  const reloaded = new SQLiteDB(reloadedRaw, ':memory:');
  assert.equal(createSessionHostContextDelivery(reloaded, 'relay', 'codex', 'thread').delivered, true);
  const metadata = JSON.parse(String(reloaded.get('SELECT engine_metadata FROM sessions')?.engine_metadata));
  assert.deepEqual(metadata.existing, { value: 1 });
  assert.equal(createSessionHostContextDelivery(reloaded, 'relay', 'codex', 'different').delivered, false);
  assert.equal(createSessionHostContextDelivery(reloaded, 'relay', 'opencode', 'thread').delivered, false);
  reloaded.run('UPDATE sessions SET context_compaction_count = 1');
  assert.equal(createSessionHostContextDelivery(reloaded, 'relay', 'codex', 'thread').delivered, false);
  raw.close();
  reloadedRaw.close();
});

test('新建会话可在引擎 ID 落库后确认，过期连接和损坏 metadata 不覆盖原数据', async () => {
  const SQL = await initSqlJs({ locateFile: () => path.resolve('node_modules/sql.js/dist/sql-wasm.wasm') });
  const raw = new SQL.Database();
  raw.exec(`CREATE TABLE sessions (id TEXT PRIMARY KEY, engine TEXT, engine_session_id TEXT, engine_metadata TEXT, deleted_at INTEGER, context_compaction_count INTEGER DEFAULT 0);
    INSERT INTO sessions VALUES ('relay', 'zcode', NULL, NULL, NULL, 0);`);
  const db = new SQLiteDB(raw, ':memory:');
  let saves = 0;
  db.saveToFile = () => { throw new Error('不得同步写盘'); };
  db.scheduleSaveToFile = () => { saves += 1; };
  const state = createSessionHostContextDelivery(db, 'relay', 'zcode', null);
  assert.equal(state.delivered, false);
  db.run("UPDATE sessions SET engine_session_id = 'new-thread'");
  state.onDelivered('new-thread');
  assert.equal(saves, 1);
  const before = db.get('SELECT engine_metadata FROM sessions')?.engine_metadata;
  state.onDelivered('old-thread');
  assert.equal(db.get('SELECT engine_metadata FROM sessions')?.engine_metadata, before);
  state.onInvalidated!('new-thread');
  assert.equal(JSON.parse(String(db.get('SELECT engine_metadata FROM sessions')?.engine_metadata)).relayHostContext, undefined);
  assert.equal(saves, 2);
  db.run("UPDATE sessions SET engine_metadata = 'invalid json'");
  state.onDelivered('new-thread');
  assert.equal(db.get('SELECT engine_metadata FROM sessions')?.engine_metadata, 'invalid json');
  db.run('UPDATE sessions SET deleted_at = 1, engine_metadata = NULL');
  state.onDelivered('new-thread');
  assert.equal(db.get('SELECT engine_metadata FROM sessions')?.engine_metadata, null);
  assert.equal(saves, 2);
  raw.close();
});
