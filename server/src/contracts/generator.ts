const INDENT = '  ';

function renderLiteral(value: unknown): string {
  if (typeof value === 'string') return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  if (value === null) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  throw new Error(`不支持的 Zod literal 值：${String(value)}`);
}

function unwrapOptional(schema: ZodTypeAny): ZodTypeAny {
  return schema instanceof z.ZodOptional ? schema.unwrap() : schema;
}

function unwrapEffects(schema: ZodTypeAny): ZodTypeAny {
  let current = schema;
  while (current instanceof z.ZodEffects) current = current.innerType();
  return current;
}

function renderObjectShape(shape: ZodRawShape, level: number, references: SchemaReferences): string {
  const indent = INDENT.repeat(level);
  return Object.entries(shape)
    .map(([name, propertySchema]) => {
      const optional = propertySchema instanceof z.ZodOptional;
      return `${indent}${name}${optional ? '?' : ''}: ${renderSchemaType(unwrapOptional(propertySchema), level, references)};`;
    })
    .join('\n');
}

type SchemaReferences = Map<ZodTypeAny, string>;

export function renderSchemaType(schema: ZodTypeAny, level = 0, references: SchemaReferences = new Map()): string {
  if (schema instanceof z.ZodDefault) return renderSchemaType(schema.removeDefault(), level, references);
  const reference = references.get(schema);
  if (reference) return reference;
  schema = unwrapEffects(schema);
  if (schema instanceof z.ZodOptional) return renderSchemaType(schema.unwrap(), level, references);
  if (schema instanceof z.ZodNullable) return `${renderSchemaType(schema.unwrap(), level, references)} | null`;
  if (schema instanceof z.ZodString) return 'string';
  if (schema instanceof z.ZodNumber) return 'number';
  if (schema instanceof z.ZodBoolean) return 'boolean';
  if (schema instanceof z.ZodLiteral) return renderLiteral(schema.value);
  if (schema instanceof z.ZodEnum) return schema.options.map(renderLiteral).join(' | ');
  if (schema instanceof z.ZodArray) {
    const elementType = renderSchemaType(schema.element, level, references);
    const needsParentheses = !references.has(schema.element) && (schema.element instanceof z.ZodEnum
      || schema.element instanceof z.ZodUnion
      || schema.element instanceof z.ZodDiscriminatedUnion);
    return `${needsParentheses ? `(${elementType})` : elementType}[]`;
  }
  if (schema instanceof z.ZodRecord) return `Record<string, ${renderSchemaType(schema.valueSchema, level, references)}>`;
  if (schema instanceof z.ZodUnknown) return 'unknown';
  if (schema instanceof z.ZodUnion) return schema.options.map((option: ZodTypeAny) => renderSchemaType(option, level, references)).join(' | ');
  if (schema instanceof z.ZodDiscriminatedUnion) {
    return schema.options.map((option: ZodTypeAny) => renderSchemaType(option, level, references)).join(' | ');
  }
  if (schema instanceof z.ZodObject) {
    const indent = INDENT.repeat(level);
    return `{\n${renderObjectShape(schema.shape, level + 1, references)}\n${indent}}`;
  }
  throw new Error(`不支持的 Zod 契约节点：${schema._def.typeName}`);
}

function renderInterface(name: string, schema: ZodTypeAny, references: SchemaReferences = new Map()): string {
  const objectSchema = unwrapEffects(schema);
  if (!(objectSchema instanceof z.ZodObject)) throw new Error(`契约 ${name} 不是对象`);
  const lines = (Object.entries(objectSchema.shape) as Array<[string, ZodTypeAny]>)
    .map(([propertyName, propertySchema]) => {
      const optional = propertySchema instanceof z.ZodOptional;
      return `${INDENT}${propertyName}${optional ? '?' : ''}: ${renderSchemaType(unwrapOptional(propertySchema), 1, references)};`;
    })
    .join('\n');
  return `export interface ${name} {\n${lines}\n}`;
}

